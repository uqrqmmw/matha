// Generated from the hash-bound private solution manifest. Keep this registry
// separate from lib.ts so page names and cross-page bindings stay auditable.
function bind(sourceId: string, files: string[], pages: number[][]) {
  if (pages.length !== 20) {
    throw new Error(`${sourceId} must bind 20 questions`);
  }
  return Object.fromEntries(pages.map((pageNumbers, index) => [
    index + 1,
    pageNumbers.map((page) => `${sourceId}/${files[page - 1]}`),
  ])) as Record<number, string[]>;
}

